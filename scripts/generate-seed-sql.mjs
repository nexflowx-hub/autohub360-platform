#!/usr/bin/env node
/**
 * Generates supabase/seed/seed.sql from packages/catalog/src/data/*.json.
 * Deterministic UUIDs via public.stable_uuid(natural_key) — same key yields the
 * same UUID in every environment. Idempotent: safe to re-run.
 *
 * Usage: node scripts/generate-seed-sql.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'packages/catalog/src/data');
const outDir = join(root, 'supabase/seed');

const categories = JSON.parse(readFileSync(join(dataDir, 'categories.json'), 'utf8'));
const brands = JSON.parse(readFileSync(join(dataDir, 'brands.json'), 'utf8'));
const products = [
  ...JSON.parse(readFileSync(join(dataDir, 'products-1.json'), 'utf8')),
  ...JSON.parse(readFileSync(join(dataDir, 'products-2.json'), 'utf8')),
  ...JSON.parse(readFileSync(join(dataDir, 'products-3.json'), 'utf8')),
];
const vehicles = JSON.parse(readFileSync(join(dataDir, 'vehicles.json'), 'utf8'));
const articles = JSON.parse(readFileSync(join(dataDir, 'articles.json'), 'utf8'));

const q = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (xs) => `array[${xs.map(q).join(',')}]`;
const jsonb = (o) => `$$${JSON.stringify(o)}$$::jsonb`;

let sql = `-- AutoHub360 Platform — deterministic demo seed (V1)
-- GENERATED by scripts/generate-seed-sql.mjs — edit the JSON sources, not this file.
-- Demo/mock catalog data: realistic but clearly separated from live operational data.

begin;

`;

// Markets (idempotent)
sql += `insert into public.markets (code, name, currency, locale, status, checkout_enabled, operator_line) values
  ('BR', 'Brasil', 'BRL', 'pt-BR', 'live', true, 'AutoHub360 Brasil — CNPJ 66.991.513/0001-10'),
  ('EU', 'Europa', 'EUR', 'pt-BR', 'preview', false, 'AutoHub360 Europe — marca operada pela Auto Lux Europe SAS')
on conflict (code) do nothing;

`;

// Categories
sql += '-- Categories\n';
for (const c of categories) {
  sql += `insert into public.categories (id, slug, name, universe, description, icon)\nvalues (public.stable_uuid('${c.id}'), ${q(c.slug)}, ${q(c.name)}, ${q(c.universe)}, ${q(c.description)}, ${q(c.icon)})\non conflict (slug) do update set name = excluded.name, universe = excluded.universe, description = excluded.description, icon = excluded.icon;\n`;
}

// Brands
sql += '\n-- Brands\n';
for (const b of brands) {
  sql += `insert into public.brands (id, slug, name)\nvalues (public.stable_uuid('${b.id}'), ${q(b.slug)}, ${q(b.name)})\non conflict (slug) do update set name = excluded.name;\n`;
}

// Products
sql += '\n-- Products\n';
for (const p of products) {
  const specs = p.specs ?? [];
  sql += `insert into public.products (id, slug, sku, category_id, brand_id, title, subtitle, description, specs, image_key, currency, price_cents, compare_at_cents, stock, weight_grams, warranty_months, universal, installable, featured, best_seller, rating, review_count, badges, published)
values (
  public.stable_uuid('${p.id}'), ${q(p.slug)}, ${q(p.sku)},
  public.stable_uuid('${p.categoryId}'), public.stable_uuid('${p.brandId}'),
  ${q(p.title)}, ${q(p.subtitle)}, ${q(p.description)}, ${jsonb(specs)}, ${q(p.imageKey)},
  ${q(p.currency)}, ${p.priceCents}, ${p.compareAtCents ?? 'null'}, ${p.stock}, ${p.weightGrams},
  ${p.warrantyMonths}, ${p.universal}, ${p.installable}, ${p.featured}, ${p.bestSeller},
  ${p.rating}, ${p.reviewCount}, ${arr(p.badges ?? [])}, true
)
on conflict (sku) do update set
  title = excluded.title, subtitle = excluded.subtitle, description = excluded.description,
  specs = excluded.specs, price_cents = excluded.price_cents,
  compare_at_cents = excluded.compare_at_cents, stock = excluded.stock,
  featured = excluded.featured, best_seller = excluded.best_seller,
  rating = excluded.rating, review_count = excluded.review_count, badges = excluded.badges,
  published = true;
`;
  // Market offer BR
  sql += `insert into public.product_market_offers (product_id, market, currency, price_cents, compare_at_cents, stock, active)
values (public.stable_uuid('${p.id}'), 'BR', ${q(p.currency)}, ${p.priceCents}, ${p.compareAtCents ?? 'null'}, ${p.stock}, true)
on conflict (product_id, market) do update set price_cents = excluded.price_cents, compare_at_cents = excluded.compare_at_cents, stock = excluded.stock, active = true;
`;
}

// Vehicles: makes -> models -> versions
sql += '\n-- Vehicles\n';
for (const m of vehicles.makes) {
  sql += `insert into public.vehicles (id, slug, name, vehicle_type)\nvalues (public.stable_uuid('${m.id}'), ${q(m.slug)}, ${q(m.name)}, ${q(m.type)})\non conflict (slug) do update set name = excluded.name, vehicle_type = excluded.vehicle_type;\n`;
}
for (const mo of vehicles.models) {
  sql += `insert into public.vehicle_models (id, vehicle_id, slug, name)\nvalues (public.stable_uuid('${mo.id}'), public.stable_uuid('${mo.makeId}'), ${q(mo.slug)}, ${q(mo.name)})\non conflict (slug) do update set name = excluded.name, vehicle_id = excluded.vehicle_id;\n`;
}
for (const v of vehicles.versions) {
  sql += `insert into public.vehicle_versions (id, model_id, name, year_start, year_end, engine, headlight_socket, canbus)\nvalues (public.stable_uuid('${v.id}'), public.stable_uuid('${v.modelId}'), ${q(v.name)}, ${v.yearStart}, ${v.yearEnd}, ${q(v.engine)}, ${v.headlightSocket ? q(v.headlightSocket) : 'null'}, ${v.canbus ?? false})\non conflict (id) do update set name = excluded.name, year_start = excluded.year_start, year_end = excluded.year_end, engine = excluded.engine, headlight_socket = excluded.headlight_socket, canbus = excluded.canbus;\n`;
}

// Compatibility: socket-based expansion for non-universal lighting + explicit non-universal entries
sql += '\n-- Product compatibility (structured fitment)\n';
const socketByProductId = new Map();
for (const p of products) {
  if (!p.universal) {
    // non-universal products in this dataset are the socket-based LED/halogen kits
    socketByProductId.set(p.id, p.socket);
  }
}
for (const [pid, socket] of socketByProductId) {
  const matches = vehicles.versions.filter((v) => v.headlightSocket === socket);
  for (const v of matches) {
    sql += `insert into public.product_compatibility (product_id, vehicle_version_id, confirmed)\nvalues (public.stable_uuid('${pid}'), public.stable_uuid('${v.id}'), true)\non conflict (product_id, vehicle_version_id) do nothing;\n`;
  }
}

// Inventory: one public warehouse + pickup point + partner workshop
sql += `
-- Inventory locations (public info only: city/state, no street address)
insert into public.inventory_locations (id, code, name, city, state, kind, is_public) values
  (public.stable_uuid('loc-go-warehouse'), 'GO-CD', 'Centro de distribuição Goiás', 'Goiânia', 'GO', 'warehouse', false),
  (public.stable_uuid('loc-anapolis-pickup'), 'ANA-PU', 'Retirada Anápolis', 'Anápolis', 'GO', 'pickup_point', true),
  (public.stable_uuid('loc-generoso-workshop'), 'ANA-GEN', 'Generoso Auto Center — parceiro de instalação', 'Anápolis', 'GO', 'partner_workshop', true)
on conflict (code) do nothing;

-- Inventory items: random-but-deterministic split between locations
`;

for (const p of products) {
  const total = p.stock;
  const half = Math.floor(total / 2);
  sql += `insert into public.inventory_items (product_id, location_id, quantity, reserved) values
  (public.stable_uuid('${p.id}'), public.stable_uuid('loc-go-warehouse'), ${total - half}, 0),
  (public.stable_uuid('${p.id}'), public.stable_uuid('loc-anapolis-pickup'), ${half}, 0)
on conflict (product_id, location_id) do update set quantity = excluded.quantity;
`;
}

// Installation services + slots (next 14 weekdays, deterministic)
sql += `
-- Installation services (Generoso Auto Center partnership)
insert into public.installation_services (id, slug, name, description, base_fee_cents, duration_minutes, active) values
  (public.stable_uuid('svc-inst-geral'), 'instalacao-geral', 'Instalação de acessório (compra AutoHub360)', 'Instalação especializada com o parceiro oficial em Anápolis - GO.', 9900, 60, true),
  (public.stable_uuid('svc-inst-som'), 'instalacao-multimidia', 'Instalação de central multimídia / som', 'Instalação com adaptação de chicote e teste completo.', 19900, 120, true),
  (public.stable_uuid('svc-inst-seguranca'), 'instalacao-seguranca', 'Instalação de rastreador / alarme / câmera', 'Instalação discreta com teste de funcionamento e orientação de uso do app.', 14900, 90, true),
  (public.stable_uuid('svc-inst-led'), 'instalacao-iluminacao', 'Instalação de kit LED com regulagem de farol', 'Troca de lâmpadas + regulagem de feixe luminoso.', 7900, 45, true)
on conflict (slug) do update set name = excluded.name, base_fee_cents = excluded.base_fee_cents, active = true;

-- Appointment slots: next 14 days from seed run, 09:00-17:00
insert into public.appointment_slots (id, service_id, slot_date, slot_time, capacity)
select
  public.stable_uuid('slot-' || s.slug || '-' || to_char(d, 'YYYY-MM-DD') || '-' || t::text),
  s.id,
  d::date,
  t,
  2
from public.installation_services s
cross join generate_series(current_date + 1, current_date + 14, interval '1 day') as g(d)
cross join (values '09:00'::time, '11:00'::time, '14:00'::time, '16:00'::time) as x(t)
where extract(dow from d) between 1 and 6
on conflict (service_id, slot_date, slot_time) do nothing;
`;

// Content posts
sql += '\n-- Editorial content\n';
for (const a of articles) {
  sql += `insert into public.content_posts (id, slug, kind, app, title, excerpt, body, category_label, image_key, read_minutes, status, published_at)
values (
  public.stable_uuid('post-${a.slug}'), ${q(a.slug)}, 'article', 'tech', ${q(a.title)}, ${q(a.excerpt)},
  ${jsonb(a.body)}, ${q(a.categoryLabel)}, ${q(a.imageKey)}, ${a.readMinutes}, 'published', ${q(a.publishedAt)}
)
on conflict (slug) do update set title = excluded.title, excerpt = excluded.excerpt, body = excluded.body, published_at = excluded.published_at;
`;
}

// Demo coupon (clearly demo)
sql += `
-- Demo coupon (clearly marked, used in checkout demo)
insert into public.coupons (id, code, kind, value, min_subtotal_cents, market, active)
values (public.stable_uuid('coupon-autohub10'), 'AUTOHUB10', 'percent', 10, 20000, 'BR', true)
on conflict (code) do update set active = true;

commit;
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'seed.sql'), sql, 'utf8');
console.log(
  `seed.sql generated: ${categories.length} categories, ${brands.length} brands, ${products.length} products, ${vehicles.versions.length} versions, ${articles.length} articles`,
);
